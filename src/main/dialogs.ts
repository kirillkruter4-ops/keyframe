/**
 * Учёт открытых системных диалогов.
 *
 * Диалог открытия файла модален окну-хозяину: пока он висит, Windows **выключает**
 * это окно. Оно перестаёт принимать мышь и не сворачивается — по ощущению
 * приложение зависает намертво. Это нормально ровно до тех пор, пока диалог
 * виден. Стоит ему уйти за окно интерфейса — и человек остаётся перед мёртвым
 * приложением без единой подсказки, что от него хотят.
 *
 * Спрятать диалог мы умеем сами: оверлей поднимается наверх при каждом
 * получении фокуса хозяином, и это поднятие перекрывает диалог. Поэтому здесь
 * счётчик: пока хоть один диалог открыт, оверлей не трогаем.
 *
 * Второй диалог поверх первого не открываем вовсе. Открыть файл можно и
 * кнопкой, и Ctrl+O, и из палитры — два модальных окна подряд гарантированно
 * оставят одно из них позади другого.
 */
let open = 0

export function dialogsOpen(): boolean {
  return open > 0
}

/**
 * Показать диалог, если ни одного ещё не открыто.
 *
 * `busy` возвращается, когда открывать нельзя: вызывающий должен вести себя
 * так же, как при отмене, — не молчать и не падать.
 */
export async function showOnlyDialog<T>(run: () => Promise<T>, busy: T): Promise<T> {
  if (open > 0) return busy

  open += 1
  try {
    return await run()
  } finally {
    open -= 1
  }
}
